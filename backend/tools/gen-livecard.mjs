// Writes the trip card code into src/worker.js from the app's own sources, so the card the server pushes is
// worked out exactly like the card the app draws: app/src/lib/tripState.ts (the one live trip state, phase 2 of
// docs/TRIP_FLOW_SPEC.md), app/src/lib/liveCalc.ts (computeLive) and app/platform/tripCard.ts (cardFor, staleAt).
// Each file runs in its own scope; tripState's exports are handed to the next two (their imports of it are inlined).
// Run after changing any of them:
//   node tools/gen-livecard.mjs          (needs app/node_modules for TypeScript)
//   node tools/gen-livecard.mjs --check  (exit 1 when worker.js is out of date)
// app/test/livecard-sync.test.mjs runs the check with the app's tests.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const app = path.resolve(root, "../app");
const START = "// ---- live card start (generated by tools/gen-livecard.mjs, do not edit by hand)";
const END = "// ---- live card end";
const FILES = [["tripState", "src/lib/tripState.ts"], ["liveCalc", "src/lib/liveCalc.ts"], ["tripCard", "platform/tripCard.ts"]];
// imports of a file inlined before it in the block
const INLINED = /^import\s+\{[^}]*\}\s+from\s+['"](?:\.\/|\.\.\/src\/lib\/)(tripState|liveCalc)['"];?\s*$/gm;

const exportsOf = (js) => [...js.matchAll(/^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);

export function liveCardBlock(ts) {
  const shared = [];
  const parts = FILES.map(([name, rel]) => {
    const src = fs.readFileSync(path.join(app, rel), "utf8");
    let js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, removeComments: true } }).outputText;
    js = js.replace(INLINED, "");
    if (/^\s*import\s/m.test(js)) throw new Error(rel + " has a runtime import; the server copy needs it inlined");
    const names = exportsOf(js);
    js = js.replace(/^export\s+/gm, "").replace(/^export\s*\{\s*\};?\s*$/gm, "").trim();
    const body = js.split("\n").map((l) => (l ? "    " + l : l)).join("\n");
    const out = [`  // ${rel}`, `  const ${name} = (() => {`, body, `    return { ${names.join(", ")} };`, "  })();"];
    if (name === "tripState") { out.push(`  const { ${names.join(", ")} } = tripState;`); shared.push(...names); }
    return out.join("\n");
  });
  return [START, "const LIVECARD = (() => {", ...parts,
    "  return { computeLive: liveCalc.computeLive, cardFor: tripCard.cardFor, staleAt: tripCard.staleAt, cardWarning: tripCard.cardWarning, legNoteFor: tripCard.legNoteFor, " + shared.join(", ") + " };",
    "})();", END].join("\n");
}

export function withBlock(worker, block) {
  const a = worker.indexOf(START), b = worker.indexOf(END);
  if (a < 0 || b < a) throw new Error("live card markers not found in worker.js");
  return worker.slice(0, a) + block + worker.slice(b + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname) {
  const ts = createRequire(path.join(app, "package.json"))("typescript");
  const file = path.join(root, "src/worker.js");
  const cur = fs.readFileSync(file, "utf8");
  const next = withBlock(cur, liveCardBlock(ts));
  if (process.argv.includes("--check")) {
    if (next !== cur) { console.error("src/worker.js live card block is out of date: node tools/gen-livecard.mjs"); process.exit(1); }
    console.log("live card block up to date");
  } else {
    fs.writeFileSync(file, next);
    console.log(next === cur ? "unchanged" : "updated src/worker.js");
  }
}
