// Writes migrations/0001_init.sql for a fresh D1 database from the CREATE statements in
// src/worker.js (the worker also creates its tables on first use, so this file and the code
// cannot drift: test/hosts.test.mjs checks the file matches). Usage: node tools/schema.mjs [--check]
import fs from "node:fs";
import path from "node:path";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");

export function schemaSql(src) {
  const creates = [];
  for (const m of src.matchAll(/(CREATE (?:UNIQUE )?(?:TABLE|INDEX) IF NOT EXISTS [\s\S]*?)[`"]\s*\)/g)) {
    const s = m[1].replace(/\s+/g, " ").trim();
    if (!creates.includes(s)) creates.push(s);
  }
  const tables = creates.filter((s) => s.startsWith("CREATE TABLE"));
  const indexes = creates.filter((s) => !s.startsWith("CREATE TABLE"));
  // Columns added later with ALTER TABLE: kept only when the CREATE does not have them yet.
  const alters = [];
  for (const m of src.matchAll(/ALTER TABLE (\w+) ADD COLUMN (\w+) ([A-Z]+[^"`]*)[`"]/g)) {
    const create = tables.find((t) => t.startsWith(`CREATE TABLE IF NOT EXISTS ${m[1]} `));
    if (create && !new RegExp(`[(,]\\s*${m[2]}\\s`).test(create)) alters.push(`ALTER TABLE ${m[1]} ADD COLUMN ${m[2]} ${m[3].trim()}`);
  }
  const head = "-- Transport: Sydney Live, D1 schema for a fresh database. Generated by tools/schema.mjs\n-- from src/worker.js; do not edit by hand. Applied once by wrangler d1 migrations apply.\n";
  return head + [...tables, ...alters, ...indexes].map((s) => s + ";").join("\n") + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const sql = schemaSql(fs.readFileSync(path.join(root, "src/worker.js"), "utf8"));
  const out = path.join(root, "migrations/0001_init.sql");
  if (process.argv.includes("--check")) {
    const ok = fs.existsSync(out) && fs.readFileSync(out, "utf8") === sql;
    console.log(ok ? "migrations/0001_init.sql is up to date" : "migrations/0001_init.sql is out of date: run node tools/schema.mjs");
    process.exit(ok ? 0 : 1);
  }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, sql);
  console.log("Wrote " + out + " (" + sql.split("\n").filter((l) => l.startsWith("CREATE TABLE")).length + " tables)");
}
