// Writes src/lib/busGroups.gen.ts from the bus route data the server serves (backend/src/public/stations):
// which route numbers run outside Sydney, and for a number used both in Sydney and elsewhere, where the Sydney
// service goes. A stop's number starts with its postcode, so a direction is in Sydney when most of its stops have
// a Sydney postcode. Run: node tools/gen-bus-groups.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const data = path.join(here, '..', '..', 'backend', 'src', 'public', 'stations');
const desc = JSON.parse(fs.readFileSync(path.join(data, 'bus-routes.json'), 'utf8'));
const all = {};
for (const f of fs.readdirSync(path.join(data, 'bus'))) Object.assign(all, JSON.parse(fs.readFileSync(path.join(data, 'bus', f), 'utf8')));

// Must match sydneyPostcode in src/lib/busCore.ts.
const sydPc = (pc) => (pc >= 2000 && pc <= 2249) || (pc >= 2555 && pc <= 2574) || (pc >= 2740 && pc <= 2772);
const inSydney = (d) => {
  const ids = (d.stops || []).map((s) => String(s[0])).filter((id) => /^\d{6,7}$/.test(id));
  return ids.length > 0 && ids.filter((id) => sydPc(+id.slice(0, 4))).length * 2 >= ids.length;
};
const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z ]/g, '');

const regional = [], sydneyTo = {};
for (const code of Object.keys(desc).sort()) {
  const dirs = all[code] || [];
  if (!dirs.length) continue;
  const syd = dirs.filter(inSydney);
  if (!syd.length) { regional.push(code); continue; }
  // The description belongs to the other service when none of its Sydney directions is named in it.
  const d = norm(desc[code]);
  if (syd.length < dirs.length && !syd.some((x) => d.includes(norm(x.to).slice(0, 12)))) sydneyTo[code] = [...new Set(syd.map((x) => x.to))].slice(0, 2);
}
const out = `// Generated by tools/gen-bus-groups.mjs from backend/src/public/stations. Do not edit by hand.
/** Bus route numbers whose services all run outside Sydney (regional NSW and coaches). */
export const REGIONAL_ROUTES: ReadonlySet<string> = new Set(${JSON.stringify(regional)});
/** Route numbers used in Sydney and elsewhere, whose listed description is the other service: where the Sydney one goes. */
export const SYDNEY_TO: Readonly<Record<string, string[]>> = ${JSON.stringify(sydneyTo)};
`;
fs.writeFileSync(path.join(here, '..', 'src', 'lib', 'busGroups.gen.ts'), out);
console.log(`regional ${regional.length}, shared numbers ${Object.keys(sydneyTo).length}`);
